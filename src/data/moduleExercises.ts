export function getModuleExerciseDeck(moduleId: string): ModuleExerciseDeck | null {
  const raw = RAW_MODULE_EXERCISES[moduleId];
  if (!raw) return null;
  return {
    moduleId,
    ...raw
  };
}

export function getAllModuleExerciseIds(): string[] {
  return Object.keys(RAW_MODULE_EXERCISES);
}

export function getTotalModuleExercisesCount(moduleId: string): number {
  return RAW_MODULE_EXERCISES[moduleId]?.exercises.length ?? 0;
}

export function getCompletedExercisesCountForModule(
  moduleId: string,
  completedMap: Record<string, boolean>
): number {
  const items = RAW_MODULE_EXERCISES[moduleId]?.exercises || [];
  return items.filter((ex) => !!completedMap[ex.id]).length;
}
